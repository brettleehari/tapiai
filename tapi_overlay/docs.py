"""Leaf 8 - Coding-agent docs generator.

Writes README.md and QUERIES.md into the datasource so that when the folder is
handed to a coding agent, the agent immediately understands the layout, the
TAPI data model, and where to look to answer common questions.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:  # pragma: no cover
    from .crawler import HarvestReport
    from .datasource import DataSource


def _counts_table(report: HarvestReport) -> str:
    if not report.entity_counts:
        return "_No entities harvested._\n"
    lines = ["| Entity kind | Count |", "| --- | --- |"]
    for kind in sorted(report.entity_counts):
        lines.append(f"| `{kind}` | {report.entity_counts[kind]} |")
    return "\n".join(lines) + "\n"


def _subtree_table(report: HarvestReport) -> str:
    lines = ["| Subtree | HTTP | Status |", "| --- | --- | --- |"]
    for key in sorted(report.subtrees):
        s = report.subtrees[key]
        state = "ok" if s.get("ok") else (s.get("note") or f"HTTP {s.get('status')}")
        lines.append(f"| `{key}` | {s.get('status')} | {state} |")
    return "\n".join(lines) + "\n"


def render_readme(report: HarvestReport) -> str:
    return f"""# TAPI Network Datasource

Auto-generated by **tapi-overlay** from a TAPI 2.5 (TR-547 NBI) controller.
This folder is a *snapshot of the whole network as data*. It is meant to be
handed to a coding agent as a repository: read the files, answer questions.

- Controller: `{report.endpoint}`
- Harvested: `{report.started_at}` -> `{report.finished_at}`
- Profile: TAPI 2.5 northbound (RESTCONF + JSON). No NETCONF/XML - NBI only.

## Layout

```
MANIFEST.json          What was fetched, when, from where, with counts + warnings.
raw/                   Verbatim controller responses. The source of truth.
entities/<kind>/*.json One JSON file per entity (one topology, node, link, ...).
index/                 Summary tables (CSV) + topology-graph.json for fast lookup.
schema/                TAPI YANG tree maps (the data model each entity conforms to).
README.md              This file.
SCHEMA.md              Index of the schema/ model maps.
QUERIES.md             How to answer common network questions from these files.
```

The endpoint catalog and coverage are generated directly from the ONMI TAPI
OpenAPI specs, so all TAPI modules are harvested when the controller implements
them: topology, connectivity, path-computation, OAM, fault-management,
equipment, virtual-network, streaming, notifications, plus technology-specific
detail (photonic-media/L0, digital-otn/L1, ethernet/L2) carried inside entities.

Every entity file carries two helper fields the overlay adds:
`_id` (the uuid) and `_name` (the resolved human name). Topology children also
carry `_topology` (and nodes-edge-points carry `_node`) so you can trace
ownership without re-walking the tree.

## What was collected

{_subtree_table(report)}

## Entity counts

{_counts_table(report)}

## Where things live

- **Customer edges** -> `entities/service-interface-point/` and `index/service-interface-points.csv`
- **Topology** -> `entities/topology/`, `entities/node/`, `entities/link/`, `entities/node-edge-point/`
- **Reachability / paths** -> `index/topology-graph.json` (nodes, edges, adjacency)
- **Services** -> `entities/connectivity-service/`, `entities/connection/`
- **Path computation** -> `entities/path-comp-service/`, `entities/path/`
- **Inventory** -> `entities/device/`, `entities/physical-span/`
- **Current alarms** -> `entities/active-condition/` + `index/active-conditions.csv`
- **OAM** -> `entities/oam-job/`, `entities/meg/`, PM data entities
- **Notifications / subscriptions** -> `entities/notification/`, `entities/notif-subscription/`
- **Data model** -> `schema/*.tree` (what each entity kind's fields mean)

## Refreshing

Two ways:
- **Full re-harvest**: re-run `harvest` against the same `--out` directory.
  Filenames are deterministic (uuid-based), so you get a clean git diff of what
  changed, and entities deleted upstream are pruned.
- **Incremental (TR-548 streaming)**: run `tapi-overlay stream --out <dir>` to
  apply live change records - each updates or deletes a single entity file
  in place, keeping the datasource fresh without a full re-pull.
"""


def render_queries() -> str:
    return """# Answering questions from this datasource

This datasource mirrors the TAPI 2.5 information model. Below: common questions
and exactly where to look. Prefer `index/` for aggregate questions and
`entities/` for per-object detail; `raw/` is ground truth when in doubt.

## Topology & inventory
- **How many nodes / links?** -> `index/nodes.csv`, `index/links.csv` (row counts),
  or `index/topology-graph.json` -> `stats`.
- **What are a node's details?** -> `entities/node/<uuid>.json`.
- **Which node owns a given NEP?** -> `entities/node-edge-point/<uuid>.json` -> `_node`.
- **What physical devices exist?** -> `entities/device/`.

## Reachability & paths
- **Is node A reachable from node B?** -> `index/topology-graph.json` -> `adjacency`;
  BFS over it (the overlay's `graph.shortest_path` does this).
- **What is a node's degree / is it isolated?** -> `topology-graph.json` ->
  `nodes[].degree` and `stats.isolated_nodes`.

## Services
- **What connectivity services exist and their state?** ->
  `index/connectivity-services.csv`, detail in `entities/connectivity-service/`.
- **What connections realize a service?** -> the service file's
  `connection` refs, resolved against `entities/connection/`.

## Edges / demarcation
- **What are the customer-facing SIPs?** -> `index/service-interface-points.csv`.
- **Which SIP backs a service?** -> connectivity-service `end-point[].service-interface-point`.

## State & health
- **Which objects are down / disabled?** -> filter any `index/*.csv` on
  `operational_state = DISABLED` or `administrative_state = LOCKED`.
- **What alarms are active, and how severe?** -> `index/active-conditions.csv`
  (perceived-severity, probable-cause), detail in `entities/active-condition/`.
- **Notifications / subscriptions?** -> `entities/notification/`, `entities/notif-subscription/`.

## Technology layers (optical)
- **What layer is an entity at?** -> `layer_protocol_name` column in the CSV
  indexes, or `layer-protocol-name` in the entity JSON.
- **Wavelength / OTN / Ethernet detail?** -> inside the node/NEP/CEP entity JSON
  as technology augmentations; consult `schema/tapi-photonic-media.tree`,
  `schema/tapi-digital-otn.tree`, `schema/tapi-eth.tree` for field meanings.

## Tips for the coding agent
- TAPI keys are module-prefixed (`tapi-topology:node`); the overlay's entity
  files preserve original keys, so match on the suffix if a prefix varies.
- TAPI `name` is a list of `{value-name, value}` pairs; `_name` already resolves
  the best label for you.
- When an answer needs a field not in an index, open the entity JSON - every
  raw attribute the controller returned is preserved there.
"""


def write_docs(ds: DataSource, report: HarvestReport) -> None:
    ds.write_text("README.md", render_readme(report))
    ds.write_text("QUERIES.md", render_queries())
